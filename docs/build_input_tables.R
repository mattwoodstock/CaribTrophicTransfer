# Regenerates docs/stcroix_input_values.md from the St. Croix project CSVs.
# Run from the repository root:  Rscript docs/build_input_tables.R
dir <- "Projects/StCroix_Trap/data"
md_table <- function(df, max_rows = Inf) {
  df <- utils::head(df, max_rows)
  df[] <- lapply(df, function(x) { x <- as.character(x); x[is.na(x)] <- ""; gsub("\\|", "/", x) })
  c(paste("|", paste(names(df), collapse = " | "), "|"),
    paste("|", paste(rep("---", ncol(df)), collapse = " | "), "|"),
    apply(df, 1, function(r) paste("|", paste(r, collapse = " | "), "|")))
}
rd <- function(f) utils::read.csv(file.path(dir, f), stringsAsFactors = FALSE, check.names = FALSE)
out <- c("# St. Croix Input Values (auto-generated)", "",
         "Generated by `docs/build_input_tables.R` from `Projects/StCroix_Trap/data/`. Do not edit by hand.",
         "Values flagged `PLACEHOLDER` must be replaced with real data before management use.", "")
for (f in c("settings.csv", "habitats.csv", "groups.csv", "diet.csv", "habitat_preference.csv", "gears.csv",
            "env_response.csv", "disturbances.csv", "benchmarks.csv", "scenarios.csv")) {
  out <- c(out, paste0("## ", f), "", md_table(rd(f)), "")
}
L <- rd("landings.csv")
agg <- aggregate(landings_lb ~ group + gear, data = L[L$year >= 2022, ], FUN = function(x) round(mean(x)))
names(agg)[3] <- "mean_landings_lb_2022_2024"
out <- c(out, "## landings.csv (summary: mean 2022-2024, lb; PLACEHOLDER)", "", md_table(agg[order(agg$group), ]), "")
E <- rd("effort.csv")
out <- c(out, "## effort.csv (summary: mean 2022-2024, trips; PLACEHOLDER)", "",
         md_table(aggregate(effort ~ gear, data = E[E$year >= 2022, ], FUN = function(x) round(mean(x)))), "")
C <- rd("env_covariates.csv")
out <- c(out, "## env_covariates.csv", "", md_table(C[, c("year", "variable", "value", "units", "data_status")]), "")
I <- rd("indices.csv")
out <- c(out, "## indices.csv", "", md_table(I[, c("year", "index", "group", "value", "cv", "lambda", "data_status")]), "")
writeLines(out, "docs/stcroix_input_values.md")
message("Wrote docs/stcroix_input_values.md")
